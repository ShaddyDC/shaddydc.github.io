#!/usr/bin/env python3
"""Vendor the KaTeX CSS and fonts matching the KaTeX version built into Hugo.

Hugo renders maths to HTML at build time with its own copy of KaTeX, but the
page still needs KaTeX's stylesheet and fonts, and their class names change
between KaTeX versions. This looks up which KaTeX the current `hugo` bundles
and writes the matching files to shaddy.dev/static/{css,fonts}/katex/.

Run it inside `nix develop` so `hugo` is the flake's version.
"""

import io
import json
import os
import re
import subprocess
import sys
import tarfile
import urllib.request

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATIC_DIR = os.path.join(REPO_ROOT, "shaddy.dev", "static")
CSS_FILE = os.path.join(STATIC_DIR, "css", "katex", "katex.min.css")
FONTS_DIR = os.path.join(STATIC_DIR, "fonts", "katex")

# Hugo pins its KaTeX in the package.json of its embedded JS bundle
HUGO_PACKAGE_JSON = "https://raw.githubusercontent.com/gohugoio/hugo/v{}/internal/warpc/js/package.json"
KATEX_TARBALL = "https://registry.npmjs.org/katex/-/katex-{0}.tgz"


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def hugo_version():
    out = subprocess.run(["hugo", "version"], capture_output=True, text=True, check=True).stdout
    match = re.search(r"\bv(\d+\.\d+\.\d+)", out)
    if not match:
        sys.exit(f"Could not parse Hugo version from: {out}")
    return match.group(1)


def katex_version(hugo):
    try:
        package = json.loads(fetch(HUGO_PACKAGE_JSON.format(hugo)))
    except Exception as e:
        sys.exit(f"Could not read Hugo {hugo}'s package.json ({e}); has the path in Hugo's source moved?")
    version = package.get("dependencies", {}).get("katex") or package.get("devDependencies", {}).get("katex")
    if not version:
        sys.exit(f"Hugo {hugo}'s package.json does not list katex")
    return version.lstrip("^~")


def main():
    hugo = hugo_version()
    katex = katex_version(hugo)
    print(f"Hugo {hugo} bundles KaTeX {katex}")

    tarball = tarfile.open(fileobj=io.BytesIO(fetch(KATEX_TARBALL.format(katex))))
    files = {m.name: m for m in tarball.getmembers() if m.isfile()}

    css = tarball.extractfile(files["package/dist/katex.min.css"]).read().decode()
    css = css.replace("url(fonts/", "url(/fonts/katex/")
    css = f"/* KaTeX {katex}; generated by scripts/sync-katex-css.py */\n{css}"
    with open(CSS_FILE, "w") as f:
        f.write(css)

    # Only woff2 is shipped; every browser that matters supports it
    for name in os.listdir(FONTS_DIR):
        os.remove(os.path.join(FONTS_DIR, name))
    for name, member in files.items():
        if name.startswith("package/dist/fonts/") and name.endswith(".woff2"):
            with open(os.path.join(FONTS_DIR, os.path.basename(name)), "wb") as f:
                f.write(tarball.extractfile(member).read())


if __name__ == "__main__":
    main()
